def plural(n: int, forms: tuple[str, str, str]) -> str:
    n = abs(n)
    if n % 10 == 1 and n % 100 != 11:
        w = forms[0]
    elif 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        w = forms[1]
    else:
        w = forms[2]
    return f"{n} {w}"


def shifts_word(n): return plural(n, ("смена", "смены", "смен"))
def days_word(n): return plural(n, ("день", "дня", "дней"))


def num(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def money(x: float) -> str:
    s = f"{x:,.2f}".replace(",", " ").replace(".", ",")
    return f"{s} €"
